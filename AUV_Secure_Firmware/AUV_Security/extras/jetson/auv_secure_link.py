#!/usr/bin/env python3
"""
auv_secure_link.py - Jetson / GCS side of the AUV secure link.

Byte-for-byte compatible with the STM32 library (AUV_Security, protocol v1):
AES-256-GCM, 19-byte authenticated header, nonce = epoch|counter|src|dst|0|0,
strict counter replay protection and the boot-epoch "echo" freshness rule.

Requires:  pip install cryptography pyserial
Keys:      generated by tools/gen_keys.py  (jetson_keys.json, keep private:
           chmod 600, never commit)

Usage (Jetson <-> Master over UART):
    python3 auv_secure_link.py --port /dev/ttyTHS1 --baud 1000000 \
        --keys jetson_keys.json --state-dir /var/lib/auv

The Jetson holds K5 (decrypt Master telemetry) and K6 (encrypt commands).
Telemetry arrives in an envelope [node id | original epoch | original counter
| payload]; NodeFreshness rejects stale or replayed node data end to end and
remembers the last seen (epoch, counter) per node across Jetson restarts.
"""
import argparse
import json
import os
import struct
import time

from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.exceptions import InvalidTag

VERSION = 0x01
SYNC = b"\xA5\x5A"
HEADER_SIZE = 19
TAG_SIZE = 16
MAX_PAYLOAD = 80
OVERHEAD = HEADER_SIZE + TAG_SIZE
EPOCH_LIMIT = 0xFFFFFFF0
COUNTER_LIMIT = 0xFFFFFFF0
LINK_TIMEOUT_S = 0.200
FRAME_GAP_S = 0.005
MAX_AUTH_PER_SEC = 400

ID_MASTER, ID_JETSON, ID_THRUSTER, ID_SENSOR, ID_IMU = 0x01, 0x02, 0x10, 0x11, 0x12
TYPE_HEARTBEAT, TYPE_TELEMETRY, TYPE_COMMAND, TYPE_STATUS = 0x01, 0x10, 0x20, 0x30
KNOWN_TYPES = {TYPE_HEARTBEAT, TYPE_TELEMETRY, TYPE_COMMAND, TYPE_STATUS}


class SecurityError(Exception):
    pass


# --------------------------------------------------------------------------
# Persistent boot epoch (power-loss safe: two files, write-new-then-fsync)
# --------------------------------------------------------------------------
class EpochStore:
    """Same rule as the MCU: +1 every start, persisted and fsync'ed BEFORE
    the first packet; if no valid record exists, refuse to start."""

    def __init__(self, path):
        self.paths = [path + ".a", path + ".b"]

    @staticmethod
    def _read(p):
        try:
            with open(p, "rb") as f:
                raw = f.read(12)
            magic, e, inv = struct.unpack("<III", raw)
            if magic == 0x31455541 and inv == (~e & 0xFFFFFFFF) and 0 < e <= EPOCH_LIMIT:
                return e
        except (OSError, struct.error):
            pass
        return 0

    def highest(self):
        return max(self._read(p) for p in self.paths)

    def _write(self, p, e):
        tmp = p + ".tmp"
        fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        try:
            os.write(fd, struct.pack("<III", 0x31455541, e, ~e & 0xFFFFFFFF))
            os.fsync(fd)
        finally:
            os.close(fd)
        os.replace(tmp, p)
        dfd = os.open(os.path.dirname(os.path.abspath(p)), os.O_RDONLY)
        try:
            os.fsync(dfd)
        finally:
            os.close(dfd)

    def next_epoch(self, allow_provision=False):
        cur = self.highest()
        if cur == 0 and not allow_provision:
            raise SecurityError("epoch store empty/corrupt: provision with --provision "
                                "and FRESH keys (see docs)")
        new = cur + 1
        if new > EPOCH_LIMIT:
            raise SecurityError("epoch exhausted: rotate keys")
        # A damaged file may have held the newest (already used) epoch: skip it.
        if any(os.path.exists(p) and self._read(p) == 0 for p in self.paths):
            new = cur + 2
        # Write BOTH files (each atomically). A crash between the two writes
        # leaves at least one file with the new value; a later corruption of
        # one file leaves the other with the newest value.
        for p in self.paths:
            self._write(p, new)
        if self.highest() != new:
            raise SecurityError("epoch write verify failed")
        return new


# --------------------------------------------------------------------------
# Packet helpers
# --------------------------------------------------------------------------
def build_nonce(src, dst, epoch, counter):
    return struct.pack("<II", epoch, counter) + bytes([src, dst, 0, 0])


def encode_header(ptype, src, dst, length, epoch, counter, echo):
    return SYNC + bytes([VERSION, ptype, src, dst, length]) + struct.pack("<III", epoch, counter, echo)


def decode_header(h):
    version, ptype, src, dst, length = h[2], h[3], h[4], h[5], h[6]
    epoch, counter, echo = struct.unpack("<III", h[7:19])
    return version, ptype, src, dst, length, epoch, counter, echo


class SecureLink:
    """One link (this device <-> one peer). Mirrors AUV_SecureLink in C++."""

    def __init__(self, local_id, peer_id, tx_key, rx_key, my_epoch):
        if len(tx_key) != 32 or len(rx_key) != 32 or tx_key == rx_key:
            raise SecurityError("bad key material")
        if local_id == peer_id or local_id in (0, 0xFF) or peer_id in (0, 0xFF):
            raise SecurityError("bad device ids")
        self.local, self.peer = local_id, peer_id
        self._tx = AESGCM(bytes(tx_key))
        self._rx = AESGCM(bytes(rx_key))
        self.my_epoch = my_epoch
        self.counter = 0
        self.peer_epoch = 0
        self.last_counter = None
        self.last_fresh = None
        self.buf = bytearray()
        self.last_byte_t = 0.0
        self.rate_window = -1
        self.rate_count = 0
        self.stats = dict(tx=0, delivered=0, auth_fail=0, replay=0, old_epoch=0,
                          stale_echo=0, header_reject=0, rate_limited=0, gap_timeout=0)

    # ---------------- TX ----------------
    def build_frame(self, ptype, payload=b""):
        if ptype not in KNOWN_TYPES:
            raise SecurityError("bad type")
        if len(payload) > MAX_PAYLOAD or (ptype == TYPE_HEARTBEAT and payload):
            raise SecurityError("bad payload length")
        if self.counter >= COUNTER_LIMIT:
            raise SecurityError("counter exhausted: restart (new epoch) required")
        c = self.counter
        self.counter += 1
        hdr = encode_header(ptype, self.local, self.peer, len(payload), self.my_epoch, c, self.peer_epoch)
        ct = self._tx.encrypt(build_nonce(self.local, self.peer, self.my_epoch, c), bytes(payload), hdr)
        self.stats["tx"] += 1
        return hdr + ct

    # ---------------- RX ----------------
    def link_up(self, now=None):
        now = time.monotonic() if now is None else now
        return self.last_fresh is not None and (now - self.last_fresh) <= LINK_TIMEOUT_S

    def _header_ok(self, h):
        version, ptype, src, dst, length, epoch, counter, echo = decode_header(h)
        if h[:2] != SYNC or version != VERSION or ptype not in KNOWN_TYPES:
            return False
        if length > MAX_PAYLOAD or (ptype == TYPE_HEARTBEAT and length):
            return False
        if src != self.peer or dst != self.local:
            return False
        if epoch == 0 or epoch > EPOCH_LIMIT or echo > EPOCH_LIMIT:
            return False
        return True

    def _next_sync(self, start):
        i = start
        while i < len(self.buf):
            if self.buf[i] == 0xA5 and (i + 1 >= len(self.buf) or self.buf[i + 1] == 0x5A):
                break
            i += 1
        return i

    def feed(self, data, now=None):
        """Feed received bytes. Returns list of (type, payload, counter) that are
        authenticated AND fresh. Never returns unauthenticated data."""
        now = time.monotonic() if now is None else now
        if self.buf and now - self.last_byte_t > FRAME_GAP_S:
            self.stats["gap_timeout"] += 1
            self.buf.clear()
        self.last_byte_t = now
        out = []
        for b in data:
            if not self.buf and b != 0xA5:
                continue
            if len(self.buf) == 1 and b != 0x5A:
                self.buf.clear()
                if b == 0xA5:
                    self.buf.append(b)
                continue
            self.buf.append(b)
            while len(self.buf) >= HEADER_SIZE:
                if not self._header_ok(self.buf[:HEADER_SIZE]):
                    self.stats["header_reject"] += 1
                    del self.buf[:self._next_sync(1)]
                    continue
                need = OVERHEAD + self.buf[6]
                if len(self.buf) < need:
                    break
                frame = bytes(self.buf[:need])
                res, consume = self._handle(frame, now)
                if consume:
                    del self.buf[:need]
                else:
                    del self.buf[:self._next_sync(1)]
                if res is not None:
                    out.append(res)
        return out

    def _handle(self, frame, now):
        _, ptype, src, dst, length, epoch, counter, echo = decode_header(frame)
        # 1. freshness pre-check (no crypto)
        if epoch < self.peer_epoch:
            self.stats["old_epoch"] += 1
            return None, False
        if epoch == self.peer_epoch and self.last_counter is not None and counter <= self.last_counter:
            self.stats["replay"] += 1
            return None, False
        # 2. DoS limiter
        w = int(now)
        if w != self.rate_window:
            self.rate_window, self.rate_count = w, 0
        if self.rate_count >= MAX_AUTH_PER_SEC:
            self.stats["rate_limited"] += 1
            return None, False
        self.rate_count += 1
        # 3. authenticate + decrypt
        try:
            pt = self._rx.decrypt(build_nonce(src, dst, epoch, counter),
                                  frame[HEADER_SIZE:], frame[:HEADER_SIZE])
        except InvalidTag:
            self.stats["auth_fail"] += 1
            return None, False
        # 4. commit freshness state (authenticated only)
        if epoch > self.peer_epoch:
            self.peer_epoch = epoch
        self.last_counter = counter
        # 5. echo must equal our current epoch
        if echo != self.my_epoch:
            self.stats["stale_echo"] += 1
            return None, True
        self.last_fresh = now
        self.stats["delivered"] += 1
        return (ptype, pt, counter), True


# --------------------------------------------------------------------------
# End-to-end freshness of forwarded node data (Sensor, IMU, Thruster)
# --------------------------------------------------------------------------
class NodeFreshness:
    """Per node: (epoch, counter) must strictly increase. Saved to a file at
    most once per second and on every epoch change, so after a Jetson restart
    only data newer than the last save is accepted. This closes the replay
    window that encrypt-only nodes would otherwise have after a Master reboot."""

    def __init__(self, path):
        self.path = path
        self.last = {}
        self.dirty_t = None
        try:
            with open(path) as f:
                self.last = {int(k): tuple(v) for k, v in json.load(f).items()}
        except (OSError, ValueError):
            pass

    def accept(self, node, epoch, counter, now):
        prev = self.last.get(node)
        if prev is not None and (epoch, counter) <= tuple(prev):
            return False
        new_epoch = prev is None or epoch != prev[0]
        self.last[node] = (epoch, counter)
        if new_epoch or self.dirty_t is None or now - self.dirty_t >= 1.0:
            self.save()
            self.dirty_t = now
        return True

    def save(self):
        tmp = self.path + ".tmp"
        with open(tmp, "w") as f:
            json.dump({str(k): list(v) for k, v in self.last.items()}, f)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, self.path)


def decode_envelope(payload):
    if len(payload) < 9:
        return None
    node = payload[0]
    epoch, counter = struct.unpack("<II", payload[1:9])
    return node, epoch, counter, bytes(payload[9:])


def decode_sensor(p):
    if len(p) != 28:
        return None
    tick, v, i, w, t, h = struct.unpack("<I5f", p[:24])
    return dict(tick=tick, voltage=v, current=i, power=w, temp=t, hum=h,
                leak_mask=p[24], relay=p[25], leak=p[26], flags=p[27])


def decode_imu(p):
    if len(p) != 57:
        return None
    vals = struct.unpack("<I13f", p[:56])
    return dict(tick=vals[0], quat=vals[1:5], accel=vals[5:8], gyro=vals[8:11], mag=vals[11:14], connected=p[56])


def decode_thruster(p):
    if len(p) != 12:
        return None
    return dict(servo=list(p[0:4]), thruster_us=struct.unpack("<H", p[4:6])[0],
                relay_mask=p[6], relay_out=p[7], state=p[8], invalid=struct.unpack("<H", p[10:12])[0])


def thruster_command(servos=(90, 90, 90, 90), thruster_us=1500, relay_mask=0):
    """Payload for a COMMAND frame to the Master: [target id][8-byte command]."""
    if len(servos) != 4 or any(not 0 <= a <= 180 for a in servos):
        raise ValueError("servo angles 0..180")
    if not 1100 <= thruster_us <= 1900:
        raise ValueError("thruster pulse 1100..1900 us")
    if relay_mask & ~0x03:
        raise ValueError("relay mask bits 0..1")
    return bytes([ID_THRUSTER]) + bytes(servos) + struct.pack("<H", thruster_us) + bytes([relay_mask, 0])


def load_keys(path):
    with open(path) as f:
        k = json.load(f)
    return bytes.fromhex(k["K6_jetson_to_master"]), bytes.fromhex(k["K5_master_to_jetson"])


def main():
    import serial  # pyserial
    ap = argparse.ArgumentParser()
    ap.add_argument("--port", default="/dev/ttyTHS1")
    ap.add_argument("--baud", type=int, default=1000000)
    ap.add_argument("--keys", required=True, help="jetson_keys.json from gen_keys.py")
    ap.add_argument("--state-dir", default=os.path.expanduser("~/.auv"))
    ap.add_argument("--provision", action="store_true",
                    help="initialise an empty epoch store (ONLY with freshly generated keys)")
    ap.add_argument("--thrust", type=int, default=1500, help="test thrust command in us (default neutral)")
    a = ap.parse_args()
    os.makedirs(a.state_dir, mode=0o700, exist_ok=True)

    epoch = EpochStore(os.path.join(a.state_dir, "epoch")).next_epoch(allow_provision=a.provision)
    tx, rx = load_keys(a.keys)
    link = SecureLink(ID_JETSON, ID_MASTER, tx, rx, epoch)
    fresh = NodeFreshness(os.path.join(a.state_dir, "node_freshness.json"))
    print("Jetson link started, epoch %d" % epoch)
    ser = serial.Serial(a.port, a.baud, timeout=0)
    cmd = thruster_command(thruster_us=a.thrust)
    next_cmd = time.monotonic()
    rejected = 0
    try:
        while True:
            now = time.monotonic()
            if now >= next_cmd:                       # 100 Hz commands (also keep the link alive)
                ser.write(link.build_frame(TYPE_COMMAND, cmd))
                next_cmd += 0.01
                if now - next_cmd > 0.05:
                    next_cmd = now + 0.01
            for ptype, payload, _ in link.feed(ser.read(4096), now):
                if ptype != TYPE_TELEMETRY:
                    continue
                env = decode_envelope(payload)
                if env is None:
                    continue
                node, ep, ctr, body = env
                if not fresh.accept(node, ep, ctr, now):
                    rejected += 1                    # stale / replayed node data
                    continue
                dec = {ID_SENSOR: decode_sensor, ID_IMU: decode_imu, ID_THRUSTER: decode_thruster}.get(node)
                data = dec(body) if dec else None
                if data is not None and ctr % 100 == 0:     # print about once per second per node
                    print("node 0x%02x: %s" % (node, data))
            time.sleep(0.0005)
    finally:
        fresh.save()
        print(link.stats, "stale node packets rejected:", rejected)


if __name__ == "__main__":
    main()
